// sw.js must match what website/tools/generate-sw-precache.mjs would write:
// same launch-shell PRECACHE block, worker version = AP_ASSET_V, release pins agree.
import { readFileSync, existsSync } from 'node:fs'
import { checkWorker, formatPrecache, replacePrecache } from './website/tools/generate-sw-precache.mjs'

let pass = 0, fail = 0
const ok = (name, cond, detail = '') => { if (cond) { pass++ } else { fail++; console.log('  ✗ ' + name + (detail ? '\n    ' + detail : '')) } }

const sw = readFileSync('website/sw.js', 'utf8')
const tool = sw.match(/PRECACHE_BEGIN — generated by (tools\/[\w./-]+)/)
ok('sw.js names its generator', !!tool)
ok('the named generator exists (paths are relative to website/)', !!tool && existsSync(`website/${tool[1]}`))

const result = checkWorker()
ok('sw.js matches the generator output, version and release pins', result.problems.length === 0, result.problems.join('\n    '))
ok('launch shell is small (<= 84 entries, < 3 MB)', result.entries.length <= 84 && result.bytes < 3_000_000)
ok('home and offline page are precached', result.entries.includes('./index.html') && result.entries.includes('./offline.html'))
ok('responsive story art stays runtime-only', !result.entries.some((e) => e.includes('natal-plate')))

// The check really detects drift: drop one entry and the block no longer matches.
const block = formatPrecache(result.entries)
ok('regenerating an in-sync sw.js changes nothing', replacePrecache(sw, block) === sw)
ok('a missing entry is detected', replacePrecache(sw, formatPrecache(result.entries.slice(1))) !== sw)

console.log(`\ntest-sw-precache: ${pass} passed, ${fail} failed`)
if (fail) process.exit(1)
