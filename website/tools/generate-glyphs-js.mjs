#!/usr/bin/env node
/**
 * Builds js/ap-glyphs.js from the brand glyph sprite (tools/brand-src/ap-glyphs-sprite.svg,
 * hand-drawn stroke symbols: 10 bodies + 12 signs). The script gives the Paper & Night
 * guide pages the brand glyphs in place of the retired celestial-seal art:
 *   - window.AstroIcons.planet(name, opts) / .sign(name, opts) / .orb(glyph, variant, opts)
 *     (only defined when the legacy icons.js is not on the page)
 *   - [data-celestial-seal="planet:mars" | "zodiac:leo"] spans are filled with the glyph.
 *
 * Run from website/:
 *   node tools/generate-glyphs-js.mjs           (write js/ap-glyphs.js)
 *   node tools/generate-glyphs-js.mjs --check   (exit 1 if js/ap-glyphs.js is stale)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPRITE_PATH = join(SITE, '..', 'tools', 'brand-src', 'ap-glyphs-sprite.svg');
const OUT_PATH = join(SITE, 'js', 'ap-glyphs.js');

export const PLANETS = ['sun', 'moon', 'mercury', 'venus', 'mars', 'jupiter', 'saturn', 'uranus', 'neptune', 'pluto'];
export const SIGNS = ['aries', 'taurus', 'gemini', 'cancer', 'leo', 'virgo', 'libra', 'scorpio', 'sagittarius', 'capricorn', 'aquarius', 'pisces'];

export function buildGlyphsJs() {
  const sprite = readFileSync(SPRITE_PATH, 'utf8');
  const symbols = [...sprite.matchAll(/<symbol id="g-([a-z]+)"[\s\S]*?<\/symbol>/g)];
  const ids = symbols.map((m) => m[1]);
  for (const id of [...PLANETS, ...SIGNS]) if (!ids.includes(id)) throw new Error(`g-${id} missing from ${SPRITE_PATH}`);
  const inner = symbols.map((m) => m[0]).join('');
  return `/* AstroPrecise brand glyphs for the Paper & Night guide pages.
   GENERATED by tools/generate-glyphs-js.mjs from tools/brand-src/ap-glyphs-sprite.svg.
   Do not edit by hand: change the sprite and re-run the generator. */
(function () {
  'use strict';
  var SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" class="ap-glyph-sprite" aria-hidden="true" focusable="false" style="position:absolute;width:0;height:0;overflow:hidden">${inner}</svg>`)};
  var PLANETS = ${JSON.stringify(PLANETS)};
  var SIGNS = ${JSON.stringify(SIGNS)};
  var GLYPHS = { '\\u2609': 'sun', '\\u263D': 'moon', '\\u263F': 'mercury', '\\u2640': 'venus', '\\u2642': 'mars', '\\u2643': 'jupiter', '\\u2644': 'saturn', '\\u2645': 'uranus', '\\u2646': 'neptune', '\\u2647': 'pluto' };

  function mount() {
    if (document.getElementById('ap-glyph-sprite') || !document.body) return;
    var holder = document.createElement('div');
    holder.id = 'ap-glyph-sprite';
    holder.innerHTML = SPRITE;
    document.body.insertBefore(holder, document.body.firstChild);
  }
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; });
  }
  function svg(id, opts) {
    opts = opts || {};
    mount();
    var size = opts.lg ? ' ap-glyph-i--lg' : opts.sm ? ' ap-glyph-i--sm' : '';
    var a11y = opts.label && !opts.hidden ? ' role="img" aria-label="' + esc(opts.label) + '"' : ' aria-hidden="true"';
    return '<svg class="ap-glyph-i ap-glyph-i--' + id + size + '" viewBox="0 0 24 24" focusable="false"' + a11y + '><use href="#g-' + id + '"></use></svg>';
  }
  function slug(name, list, fallback) {
    var k = String(name || '').trim().toLowerCase();
    return list.indexOf(k) >= 0 ? k : fallback;
  }
  var api = {
    planet: function (name, opts) { return svg(slug(name, PLANETS, 'sun'), opts); },
    sign: function (name, opts) { return svg(slug(name, SIGNS, 'aries'), opts); },
    orb: function (glyph, variant, opts) {
      var v = String(variant || '').toLowerCase();
      if (PLANETS.indexOf(v) >= 0 || SIGNS.indexOf(v) >= 0) return svg(v, opts);
      return svg(GLYPHS[glyph] || 'sun', opts);
    },
    brand: true
  };
  if (!window.AstroIcons) window.AstroIcons = api;
  window.APGlyphs = api;

  function hydrate() {
    mount();
    var nodes = document.querySelectorAll('[data-celestial-seal]');
    for (var i = 0; i < nodes.length; i++) {
      var parts = String(nodes[i].getAttribute('data-celestial-seal')).split(':');
      var id = parts[1] && (parts[0] === 'planet' ? slug(parts[1], PLANETS, '') : parts[0] === 'zodiac' ? slug(parts[1], SIGNS, '') : '');
      if (id) nodes[i].innerHTML = svg(id, { sm: nodes[i].hasAttribute('data-seal-sm'), lg: nodes[i].hasAttribute('data-seal-lg') });
      else nodes[i].hidden = true;
      nodes[i].removeAttribute('data-celestial-seal');
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', hydrate);
  else hydrate();
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildGlyphsJs();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT_PATH, 'utf8'); } catch {}
    if (have !== next) { console.error('js/ap-glyphs.js is stale: run node tools/generate-glyphs-js.mjs (from website/)'); process.exit(1); }
    console.log('js/ap-glyphs.js matches the glyph sprite');
  } else {
    writeFileSync(OUT_PATH, next);
    console.log(`wrote js/ap-glyphs.js (${next.length} bytes)`);
  }
}
